	// `make_job_card` (core) always inserts as Draft (same as the standard
	// Work Order form's own "Create Job Card" button) — Job Cards get
	// submitted later from time-log activity, not at creation.
	function saveJobCardDialog(dialog, workOrder) {
		var selected = dialog.fields_dict.operations.grid.get_selected_children();
		if (!selected.length) {
			frappe.msgprint(__('Select at least one operation row (checkbox on the left) to create a Job Card for.'));
			return;
		}
		frappe.call({
			method: 'erpnext.manufacturing.doctype.work_order.work_order.make_job_card',
			args: { work_order: workOrder, operations: selected },
			freeze: true,
			freeze_message: __('Creating Job Card(s)…'),
			callback: function () {
				frappe.show_alert({ message: __('Job Card(s) created.'), indicator: 'green' });
				dialog.hide();
				loadTrail(workOrder);
			},
		});
	}

	// ── Material Request popup: create + view/edit, in place of navigating ──
