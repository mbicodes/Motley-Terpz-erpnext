	function submitWoPickerDialog(dialog) {
		var values = dialog.get_values();
		if (!values) return;
		var isFg = values.create_as === __('Work Order (FG)');

		frappe.call({
			method: 'frappe.client.get',
			args: { doctype: 'Material Request', name: values.material_request },
			callback: function (r) {
				if (!r.message) return;
				var doc = r.message;

				if (doc.material_request_type !== 'Manufacture') {
					frappe.msgprint(__('{0} is not a Manufacture-type Material Request.', [doc.name]));
					return;
				}
				if (isFg && (!doc.custom_finished_goods || !doc.custom_finished_goods.length)) {
					frappe.msgprint(__('{0} has no Finished Goods rows — pick "Work Order" instead, or add Finished Goods to it first.', [doc.name]));
					return;
				}

				var runIt = function (mrName) {
					if (isFg) runFgWorkOrders(mrName, dialog); else runPlainWorkOrder(mrName, dialog);
				};

				if (doc.docstatus === 1) {
					runIt(doc.name);
					return;
				}

				// Still Draft — this picker doesn't edit the MR, so just submit
				// it as-is first (same as clicking Submit on it), then raise
				// the Work Order — one click covers both.
				frappe.call({
					method: 'frappe.client.submit',
					args: { doc: doc },
					freeze: true,
					freeze_message: __('Submitting Material Request…'),
					callback: function (sr) {
						runIt((sr.message && sr.message.name) || doc.name);
					},
				});
			},
		});
	}

