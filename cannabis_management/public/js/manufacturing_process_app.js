	// Builds the Stock Entry the exact same way the standard Work Order form's
	// "Material Transfer" / "Manufacture" buttons do (same mapped-doc method),
	// but reviews/edits it in a popup here instead of opening the full form.
	function createStockEntry(purpose) {
		if (!currentWorkOrder) return;
		frappe.xcall('erpnext.manufacturing.doctype.work_order.work_order.make_stock_entry', {
			work_order_id: currentWorkOrder,
			purpose: purpose,
		}).then(function (stock_entry) {
			if (!stock_entry) return;
			openStockEntryDialog(stock_entry, purpose);
		});
	}

