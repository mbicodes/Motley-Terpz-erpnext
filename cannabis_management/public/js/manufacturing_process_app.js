	// Fallback for every other doctype (Item, Warehouse, Project, Sales
	// Order, Production Plan, …) — driven entirely by that doctype's own
	// meta, so it never needs hand-written field lists: only fields the
	// doctype itself marks in_list_view/bold/mandatory show up, which is
	// exactly what keeps this from turning into a "show every field" dump.
	function openGenericDocPopup(doctype, name) {
		var SKIP_TYPES = ['Section Break', 'Column Break', 'Tab Break', 'HTML', 'Button', 'Table',
			'Table MultiSelect', 'Fold', 'Heading', 'Attach', 'Attach Image', 'Signature', 'Geolocation',
			'Barcode', 'Password'];

		frappe.model.with_doctype(doctype, function () {
			frappe.call({
				method: 'frappe.client.get',
				args: { doctype: doctype, name: name },
				callback: function (r) {
					if (!r.message) return;
					var doc = r.message;
					var meta = frappe.get_meta(doctype);

					var fields = (meta.fields || []).filter(function (df) {
						if (SKIP_TYPES.indexOf(df.fieldtype) !== -1 || !df.label) return false;
						return df.in_list_view || df.bold || df.reqd || df.fieldname === meta.title_field;
					});
					if (!fields.length) {
						fields = (meta.fields || []).filter(function (df) {
							return SKIP_TYPES.indexOf(df.fieldtype) === -1 && df.label;
						});
					}
					fields = fields.slice(0, 10);

					var dialog = new frappe.ui.Dialog({
						title: __(doctype) + ' — ' + (doc[meta.title_field] || name),
						fields: fields.map(function (df) {
							return Object.assign({}, df, { read_only: 1, default: doc[df.fieldname] });
						}),
					});
					dialog.set_secondary_action_label(__('Close'));
					dialog.set_secondary_action(function () { dialog.hide(); });
					dialog.show();
				},
			});
		});
	}

