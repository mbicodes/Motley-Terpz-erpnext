	// Regenerate Finished Goods rows: one per (Raw Material × Routing operation),
	// exactly like the full Material Request form does when Routing changes.
	// Each Item can declare which Operation it's produced by
	// (Item.custom_operation) — use that to auto-fill the Finished Item for
	// each operation instead of leaving it for the user to pick, wherever
	// exactly one Item matches; otherwise it's left blank for you to pick.
	function rebuildFgRows(dialog) {
		var routing = dialog.get_value('custom_routing');
		var rmRows = (dialog.fields_dict.items.df.data || []).filter(function (r) { return r.item_code; });

		if (!routing) {
			frappe.msgprint(__('Select a Routing first.'));
			return;
		}
		if (!rmRows.length) {
			frappe.msgprint(__('Add Raw Material rows first.'));
			return;
		}

		frappe.call({
			method: 'frappe.client.get',
			args: { doctype: 'Routing', name: routing },
			callback: function (r) {
				var opNames = ((r.message && r.message.operations) || [])
					.slice().sort(function (a, b) { return a.idx - b.idx; })
					.map(function (o) { return o.operation; });

				if (!opNames.length) { frappe.msgprint(__('Routing {0} has no operations.', [routing])); return; }

				frappe.call({
					method: 'frappe.client.get_list',
					args: {
						doctype: 'Item',
						filters: { custom_operation: ['in', opNames] },
						fields: ['name', 'custom_operation', 'custom_yield_percentage'],
						limit_page_length: 0,
					},
					callback: function (r2) {
						var itemsByOp = {};
						(r2.message || []).forEach(function (it) {
							(itemsByOp[it.custom_operation] = itemsByOp[it.custom_operation] || []).push(it);
						});

						var rows = [];
						rmRows.forEach(function () {
							opNames.forEach(function (op) {
								var matches = itemsByOp[op] || [];
								// Only auto-fill when the match is unambiguous —
								// if more than one Item declares the same
								// Operation, leave it for the user to pick rather
								// than guess wrong.
								var auto = matches.length === 1 ? matches[0] : null;
								rows.push({
									name: frappe.utils.get_random(10), idx: rows.length + 1, __islocal: 1,
									operation: op,
									item: auto ? auto.name : '',
									expected_yield_: auto ? (parseFloat(auto.custom_yield_percentage) || 0) : 0,
									finished_qty_grams: 0, finished_qty_pounds: 0,
								});
							});
						});

						var field = dialog.fields_dict.custom_finished_goods;
						field.df.data = rows;
						field.grid.refresh();
						dialog._mp_n_ops = opNames.length;
						recalcFgYields(dialog);
					},
				});
			},
		});
	}

	// Port of the full form's calculate_finished_qty(): chains each Raw
	// Material's qty through its Routing-operation cycle applying each row's
	// Expected Yield %, same LBS→gram conversion.
	function recalcFgYields(dialog) {
		var rmRows = (dialog.fields_dict.items.df.data || []).filter(function (r) { return r.item_code; });
		var fgRows = dialog.fields_dict.custom_finished_goods.df.data || [];
		var nOps = dialog._mp_n_ops || Math.round(fgRows.length / (rmRows.length || 1)) || 1;

		var rmIdx = -1;
		var inputGrams = 0;

		fgRows.forEach(function (row, i) {
			var cyclePos = i % nOps;
			if (cyclePos === 0) {
				rmIdx++;
				var rm = rmRows[rmIdx];
				inputGrams = rm ? (parseFloat(rm.qty) || 0) * LBS_TO_GRAM : 0;
			}
			var yieldPct = parseFloat(row.expected_yield_) || 0;
			if (yieldPct > 0) {
				var outputGrams = inputGrams * (yieldPct / 100);
				row.finished_qty_grams = Math.round(outputGrams * 10000) / 10000;
				row.finished_qty_pounds = Math.round((outputGrams / LBS_TO_GRAM) * 10000) / 10000;
				inputGrams = outputGrams;
			} else {
				row.finished_qty_grams = 0;
				row.finished_qty_pounds = 0;
			}
		});

		var field = dialog.fields_dict.custom_finished_goods;
		field.df.data = fgRows;
		field.grid.refresh();
	}

	function saveMrDialog(dialog, opts) {
		if (document.activeElement && document.activeElement.blur) {
			document.activeElement.blur();
		}

		var values = dialog.get_values();
		if (!values) return; // Dialog already highlighted the missing/invalid fields

		var itemRows = dialog.fields_dict.items.df.data || [];
		var fgField = dialog.fields_dict.custom_finished_goods;
		var fgRowsRaw = fgField.df.data || [];

		// A selected Finished Item can show correctly in the cell on screen
		// yet never land in df.data — the grid's own model-sync for Link
		// cells in this kind of ad hoc (no real doctype behind it) table has
		// proven unreliable. Cross-read each currently-rendered row's LIVE
		// control value directly — that's the one thing guaranteed to match
		// what's actually visible — and use it whenever df.data disagrees.
		// This has to happen BEFORE recalcFgYields() so the qty math below
		// uses the real (just-picked) Yield %, not a stale zero.
		(fgField.grid.grid_rows || []).forEach(function (gridRow, i) {
			if (!fgRowsRaw[i] || !gridRow.columns) return;
			['item', 'expected_yield_', 'source_warehouse', 'wip_warehouse', 'target_warehouse'].forEach(function (fn) {
				var col = gridRow.columns[fn];
				var liveValue = col && col.field && col.field.get_value ? col.field.get_value() : undefined;
				if (liveValue !== undefined && liveValue !== null && liveValue !== '' && liveValue !== fgRowsRaw[i][fn]) {
					fgRowsRaw[i][fn] = liveValue;
				}
			});
		});

		if (dialog.get_value('custom_routing')) recalcFgYields(dialog);

		// Save every row that came from Routing × Raw Materials as-is —
		// Finished Item is NOT required to save a row (not mandatory on
		// Finished Goods Detail), so a row with just its auto-filled
		// Operation (Item/Yield still blank) still needs to make it into
		// the document, not get silently dropped for lacking an Item.
		var fgRows = fgRowsRaw.filter(function (r) { return r.operation; });

		var payload = {
			name: dialog._mp_name || null,
			company: values.company,
			custom_project: values.custom_project,
			custom_routing: values.custom_routing,
			set_warehouse: values.set_warehouse,
			transaction_date: values.transaction_date,
			items: itemRows.filter(function (r) { return r.item_code; }),
			custom_finished_goods: fgRows,
			submit: !!opts.submit,
		};

		frappe.call({
			method: API + 'save_material_request',
			args: { payload: payload },
			freeze: true,
			freeze_message: opts.submit ? __('Creating & Submitting…') : __('Saving…'),
			callback: function (r) {
				if (!r.message) return;
				frappe.show_alert({ message: __('Material Request {0} saved.', [r.message.name]), indicator: 'green' });
				loadRecent();
				if (opts.onSaved) {
					// Caller (e.g. Create ▾ on a still-Draft MR) is chaining
					// straight into raising a Work Order — let it drive the dialog.
					opts.onSaved(r.message.name);
				} else {
					dialog.hide();
					openMrDialog(r.message.name);
				}
			},
		});
	}

