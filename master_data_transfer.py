# Target IO
# ---------------------------------------------------------------------------


def exists(doctype, name):
    try:
        r = requests.get(
            f"{TARGET}/api/resource/{quote(doctype, safe='')}/{quote(str(name), safe='')}",
            headers=HEADERS, timeout=TIMEOUT,
        )
        return r.status_code == 200
    except Exception:
        return False


def _error_text(response):
    try:
        payload = response.json()
    except Exception:
        return (response.text or "")[:400]
    for key in ("exception", "_server_messages", "message", "exc"):
        if payload.get(key):
            return str(payload[key])[:400]
    return json.dumps(payload)[:400]


def create(doctype, payload, retries=3):
    """POST one record, dropping fields the target rejects and retrying."""
    body = dict(payload)
    last = ""

    for _ in range(retries):
        try:
            r = requests.post(
                f"{TARGET}/api/resource/{quote(doctype, safe='')}",
                headers=HEADERS, data=json.dumps(body, default=str), timeout=TIMEOUT,
            )
        except Exception as e:
            return False, f"network: {str(e)[:200]}"

        if r.status_code in (200, 201):
            return True, None

        last = _error_text(r)

        # "Unknown column 'x'" / "has no attribute 'x'" -> drop that field, retry.
        dropped = None
        for token in ("Unknown column '", "no attribute '", "Invalid fieldname '"):
            if token in last:
                candidate = last.split(token, 1)[1].split("'", 1)[0]
                if candidate in body:
                    dropped = candidate
                    break
        if dropped:
            body.pop(dropped, None)
            continue
        break

    return False, last


