def set_target_naming():
    """Make the target derive names from fields, not series.

    Without this the target mints its own Item names and the Item Price rows,
    which reference Items by name, all land on nothing.
    """
    updates = [
        ("Stock Settings", {"item_naming_by": "Item Code"}),
        ("Selling Settings", {"cust_master_name": "Customer Name"}),
        ("Buying Settings", {"supp_master_name": "Supplier Name"}),
    ]
    for doctype, values in updates:
        try:
            r = requests.put(
                f"{TARGET}/api/resource/{quote(doctype, safe='')}/{quote(doctype, safe='')}",
                headers=HEADERS, data=json.dumps(values), timeout=TIMEOUT,
            )
            print(f"  {doctype:18} {values} -> HTTP {r.status_code}")
        except Exception as e:
            print(f"  {doctype:18} FAILED: {str(e)[:150]}")


def finalize(doctype="Company"):
    """Second pass: PUT the fields we deferred at create time.

    Run this only after everything they reference exists - for Company that
    means after Warehouses, so at the very end of the transfer. Each field is
    sent individually so one unresolvable link cannot block the rest.
    """
    fields = deferred_fields(doctype)
    if not fields:
        return {}

    print(f"\n=== finalize {doctype}: restoring {len(fields)} deferred field(s) ===")
    applied = missing = 0

    for name in source_records(doctype):
        try:
            doc = frappe.get_doc(doctype, name).as_dict()
        except Exception:
            continue
        if not exists(doctype, name):
            continue

        allowed = target_fields(doctype)
        payload = {
            f: doc.get(f) for f in fields
            if doc.get(f) and f in allowed
        }
        if not payload:
            continue

        ok_fields = {}
        for field, value in payload.items():
            # Only set it if the referenced record actually landed.
            meta_field = frappe.get_meta(doctype).get_field(field)
            if meta_field and meta_field.options and not exists(meta_field.options, value):
                missing += 1
                continue
            ok_fields[field] = value

        if not ok_fields:
            continue

        try:
            r = requests.put(
                f"{TARGET}/api/resource/{quote(doctype, safe='')}/{quote(str(name), safe='')}",
                headers=HEADERS, data=json.dumps(ok_fields, default=str), timeout=TIMEOUT,
            )
            if r.status_code == 200:
                applied += len(ok_fields)
                print(f"  {name}: set {len(ok_fields)} field(s)")
            else:
                print(f"  {name}: HTTP {r.status_code} {_error_text(r)[:140]}")
        except Exception as e:
            print(f"  {name}: {str(e)[:140]}")

    print(f"  applied={applied} skipped_missing_target={missing}")
    return {"applied": applied, "missing": missing}


def run(doctypes=None, limit=None, verbose=False):
    doctypes = doctypes or DOCTYPES
    results = []
    for dt in doctypes:
        results.append(transfer(dt, limit=limit, verbose=verbose))

    print("\n" + "=" * 74)
    print(f"{'Doctype':18}{'Total':>8}{'Created':>9}{'Skipped':>9}{'Failed':>8}")
    print("-" * 74)
    tot = dict(total=0, created=0, skipped=0, failed=0)
    for r in results:
        print(f"{r['doctype']:18}{r['total']:>8}{r['created']:>9}{r['skipped']:>9}{r['failed']:>8}")
        for k in tot:
            tot[k] += r[k]
    print("-" * 74)
    print(f"{'TOTAL':18}{tot['total']:>8}{tot['created']:>9}{tot['skipped']:>9}{tot['failed']:>8}")
    return results
