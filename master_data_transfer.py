# Source read
# ---------------------------------------------------------------------------


def source_records(doctype):
    """Names in dependency-safe order (parents first for trees)."""
    if doctype in TREE_DOCTYPES:
        return frappe.get_all(doctype, pluck="name", order_by="lft asc")
    if doctype == "Item":
        return frappe.get_all(doctype, pluck="name", order_by="creation asc")
    return frappe.get_all(doctype, pluck="name", order_by="creation asc")


def transfer(doctype, limit=None, verbose=False):
    names = source_records(doctype)
    if limit:
        names = names[:limit]

    created = skipped = failed = 0
    errors = []
    started = time.time()

    for i, name in enumerate(names, 1):
        if exists(doctype, name):
            skipped += 1
            continue
        try:
            doc = frappe.get_doc(doctype, name).as_dict()
        except Exception as e:
            failed += 1
            errors.append((name, f"read failed: {str(e)[:150]}"))
            continue

        ok, err = create(doctype, clean(doc, doctype, skip=deferred_fields(doctype)))
        if ok:
            created += 1
            if verbose:
                print(f"    + {name}")
        else:
            failed += 1
            errors.append((name, err))

        if i % 250 == 0:
            print(f"    ... {i}/{len(names)}  created={created} skipped={skipped} failed={failed}",
                  flush=True)

    elapsed = time.time() - started
    print(f"  {doctype:16} total={len(names):5} created={created:5} "
          f"skipped={skipped:5} failed={failed:5}  ({elapsed:.0f}s)", flush=True)

    for name, err in errors[:8]:
        print(f"      FAIL {name}: {err[:180]}")
    if len(errors) > 8:
        print(f"      ... and {len(errors) - 8} more failures")

    # Later doctypes must see what this one just created.
    invalidate(doctype)

    return {"doctype": doctype, "total": len(names), "created": created,
            "skipped": skipped, "failed": failed, "errors": errors}


